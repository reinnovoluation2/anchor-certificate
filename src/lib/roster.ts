import { z } from 'zod';

// ── 단위과제 (기획서에 못박힌 네 가지뿐) ────────────────────────

export const 단위과제_목록 = [
  { 번호: '01', 이름: '글로벌 산학협력 선도' },
  { 번호: '02', 이름: '첨단·미래산업 외국인 인재 유치' },
  { 번호: '03', 이름: '미래 인재 글로벌 역량 강화' },
  { 번호: '07', 이름: 'AI관련 학과 지원' },
] as const;

export const 단위과제_번호들: string[] = 단위과제_목록.map((t) => t.번호);

export function 단위과제_이름(번호: string): string | undefined {
  return 단위과제_목록.find((t) => t.번호 === 번호)?.이름;
}

// ── 엑셀 헤더 (한 글자라도 다르면 업로드 거부) ──────────────────
//
// DESIGN.md "저장하는 내용" 표의 항목명과 반드시 같아야 한다.

export const 헤더 = [
  '해당연도',
  '단위과제번호',
  '프로그램번호',
  '프로그램명',
  '프로그램 영문명',
  '학번',
  '국문 이름',
  '영문 이름',
  '고려대학교 이메일',
] as const;

/** 서식 둘째 줄에 넣는 예시. 업로드할 때 이 줄과 똑같으면 건너뛴다. */
export const 예시_줄 = [
  '2026',
  '02',
  '05',
  '글로벌 인재 취업연계 프로그램',
  'Global Talent Employment Program',
  '2022740033',
  '리 웨이',
  'LI WEI',
  'li.wei@korea.ac.kr',
] as const;

// ── 한 줄의 모습 ────────────────────────────────────────────────

/** 숫자로 다루면 `01`이 `1`이 되어 관리번호가 틀어지므로 전부 글자로 다룬다. */
const 글자 = z.string().trim();

export const 명단줄_스키마 = z.object({
  해당연도: 글자.regex(/^\d{4}$/, '해당연도는 네 자리 숫자여야 합니다'),
  단위과제번호: 글자.refine(
    (v) => 단위과제_번호들.includes(v),
    `단위과제번호는 ${단위과제_번호들.join(', ')} 중 하나여야 합니다`,
  ),
  프로그램번호: 글자.regex(/^\d{2}$/, '프로그램번호는 두 자리 숫자여야 합니다 (예: 01)'),
  프로그램명: 글자.min(1, '프로그램명이 비어 있습니다'),
  // 유일하게 비워둘 수 있는 항목. 비면 영문 수료증을 발급하지 않는다.
  프로그램_영문명: z.string().trim().default(''),
  학번: 글자.regex(/^\d{10}$/, '학번은 숫자 10자리여야 합니다'),
  국문_이름: 글자.min(1, '국문 이름이 비어 있습니다'),
  영문_이름: 글자.min(1, '영문 이름이 비어 있습니다'),
  이메일: 글자.email('이메일 형식이 아닙니다'),
});

export type 명단줄 = z.infer<typeof 명단줄_스키마>;

// ── 도우미 ──────────────────────────────────────────────────────

/**
 * 이름을 비교할 때 쓰는 형태로 바꾼다.
 * 앞뒤 공백과 이름 사이 공백을 모두 없앤다. ("김 서준" → "김서준")
 * 기획서 규칙: 이름을 비교할 때 공백은 무시한다.
 */
export function 이름_맞추기(이름: string): string {
  return 이름.replace(/\s+/g, '');
}

/**
 * 발급 관리번호를 만든다. 형식: 연도-단위과제번호-프로그램번호
 * 예: 2026-02-05
 * 개인 순번은 붙이지 않는다 (기획서 4번).
 */
export function 발급_관리번호(줄: {
  해당연도: string;
  단위과제번호: string;
  프로그램번호: string;
}): string {
  return `${줄.해당연도}-${줄.단위과제번호}-${줄.프로그램번호}`;
}

/**
 * 같은 줄인지 판단하는 열쇠.
 * 연도 + 단위과제 + 프로그램 + 학번이 같으면 같은 줄로 보고 덮어쓴다.
 */
export function 명단줄_열쇠(줄: {
  해당연도: string;
  단위과제번호: string;
  프로그램번호: string;
  학번: string;
}): string {
  return `${줄.해당연도}|${줄.단위과제번호}|${줄.프로그램번호}|${줄.학번}`;
}

/** 영문 수료증을 발급할 수 있는 줄인가. */
export function 영문_발급가능(줄: 명단줄): boolean {
  return 줄.프로그램_영문명.length > 0;
}

// ── 여러 줄 한꺼번에 검사하기 ───────────────────────────────────

export type 검사오류 = { 줄번호: number; 메시지: string };

export type 검사결과 =
  | { 통과: true; 줄들: 명단줄[] }
  | { 통과: false; 오류들: 검사오류[] };

/** 엑셀에서 읽어낸 한 줄. 줄번호는 엑셀 화면에 보이는 그 번호다. */
export type 원본줄 = { 줄번호: number; 칸들: string[] };

/**
 * 엑셀에서 뽑아낸 값들을 검사한다.
 *
 * **틀린 줄이 하나라도 있으면 통째로 실패시킨다.** (기획서 규칙)
 * 절반만 저장되면 명단이 어긋난 채로 남아 무엇을 다시 올려야 할지 알 수 없다.
 *
 * 줄번호를 그대로 들고 다니는 이유는, 중간에 빈 줄이 섞여 있어도
 * 사용자에게 엑셀 화면과 같은 번호를 알려주기 위해서다.
 */
export function 명단_검사(원본줄들: 원본줄[]): 검사결과 {
  const 오류들: 검사오류[] = [];
  const 줄들: 명단줄[] = [];
  const 본_열쇠 = new Map<string, number>();

  원본줄들.forEach(({ 줄번호, 칸들 }) => {
    if (칸들.length < 헤더.length) {
      오류들.push({ 줄번호, 메시지: `칸이 ${헤더.length}개여야 하는데 ${칸들.length}개입니다` });
      return;
    }

    const 결과 = 명단줄_스키마.safeParse({
      해당연도: 칸들[0] ?? '',
      단위과제번호: 칸들[1] ?? '',
      프로그램번호: 칸들[2] ?? '',
      프로그램명: 칸들[3] ?? '',
      프로그램_영문명: 칸들[4] ?? '',
      학번: 칸들[5] ?? '',
      국문_이름: 칸들[6] ?? '',
      영문_이름: 칸들[7] ?? '',
      이메일: 칸들[8] ?? '',
    });

    if (!결과.success) {
      for (const 문제 of 결과.error.issues) {
        const 항목 = String(문제.path[0] ?? '').replace(/_/g, ' ');
        오류들.push({ 줄번호, 메시지: `${항목} — ${문제.message}` });
      }
      return;
    }

    // 파일 안에서 같은 줄이 두 번 나오면 어느 것을 쓸지 알 수 없으므로 막는다.
    const 열쇠 = 명단줄_열쇠(결과.data);
    const 앞줄 = 본_열쇠.get(열쇠);
    if (앞줄 !== undefined) {
      오류들.push({ 줄번호, 메시지: `${앞줄}번째 줄과 같은 사람·같은 프로그램입니다` });
      return;
    }
    본_열쇠.set(열쇠, 줄번호);

    줄들.push(결과.data);
  });

  if (오류들.length > 0) return { 통과: false, 오류들 };
  return { 통과: true, 줄들 };
}
